import pytest

from agent_kit.events import Event
from agent_kit.rules import check


def shell(command, cwd="/work"):
    return Event(harness="claude", tool="Bash", kind="shell", cwd=cwd, command=command)


def rules(event):
    return [v.rule for v in check(event)]


BLOCKED = [
    ("sed -i '' 's/a/b/' f", "gnu-tools"),
    ("sed -Ei '' 's/a/b/' f", "gnu-tools"),
    ("stat -f '%Sm %N' f", "gnu-tools"),
    ("date -v-2d +%F", "gnu-tools"),
    ("date -j -f %Y-%m-%d 2026-01-01 +%s", "gnu-tools"),
    ("python3 script.py", "uv-python"),
    ("cd src && python -c 'print(1)'", "uv-python"),
    (".venv/bin/python -m pytest", "uv-python"),
    ("/usr/bin/python3 x.py", "uv-python"),
    ("FOO=1 python x.py", "uv-python"),
    ("if python3 -c 1; then echo ok; fi", "uv-python"),
    ("pip install requests", "uv-python"),
    ("git config --global user.email a@b.c", "machine-config"),
    ("git config set --global user.email a@b.c", "machine-config"),
    ("git config --global --unset user.email", "machine-config"),
    ("git -C repo config --system core.editor vim", "machine-config"),
    ("echo 'Host x' >> ~/.ssh/config", "machine-config"),
    ("echo x > $HOME/.gitconfig", "machine-config"),
    ("cp creds ~/.aws/credentials", "machine-config"),
    ("ssh-keyscan github.com >> ~/.ssh/known_hosts", "machine-config"),
    ("sed -i 's/a/b/' ~/.zshrc", "machine-config"),
    ("tee -a ~/.config/git/config < snippet", "machine-config"),
    ("while true; do sleep 5; done", "sleep-loop"),
    ("until curl -sf localhost:8080; do sleep 2; done", "sleep-loop"),
    (
        'gh pr create --title x --body "fix\n\n\N{ROBOT FACE} Generated with [Claude Code](https://claude.com/claude-code)"',
        "forge-attribution",
    ),
    ('git commit -m "feat: x" -m "Co-Authored-By: Claude Opus <noreply@anthropic.com>"', "forge-attribution"),
    (
        "gh pr create --title x --body-file - <<'EOF'\nSummary\n\nThis PR was generated by Claude.\nEOF",
        "forge-attribution",
    ),
]

ALLOWED = [
    "sed -i 's/a/b/' f",
    "/usr/bin/sed -i '' 's/a/b/' f",
    "echo \"use sed -i '' on BSD\"",
    "stat -f /",
    "stat -c '%y %n' f",
    "date -d '2 days ago'",
    "uv run python script.py",
    "uv run --with rich python x.py",
    "uv pip install requests",
    "python3 --version",
    "git config --global user.email",
    "git config --global --get user.email",
    "git config --global --list",
    "git config user.email a@b.c",
    "git -c user.name=x -c user.email=y commit -m 'feat: x'",
    "cat ~/.ssh/config",
    "echo x > .gitconfig",
    "timeout 300 bash -c 'until curl -sf x; do sleep 2; done'",
    "for f in a b; do echo $f; sleep 1; done",
    "sleep 5",
    'gh pr create --title x --body "Adds detection of AI-generated content in uploads"',
    'git commit -m "fix: y" -m "Co-authored-by: Jane Doe <jane@example.com>"',
]


@pytest.mark.parametrize(("command", "rule"), BLOCKED)
def test_blocks(home, command, rule):
    assert rule in rules(shell(command))


@pytest.mark.parametrize("command", ALLOWED)
def test_allows(home, command):
    assert rules(shell(command)) == []


def test_relative_path_resolves_against_cwd(home):
    assert rules(shell("echo x > .gitconfig", cwd=str(home))) == ["machine-config"]


def test_body_file_contents_are_checked(home):
    body = home / "body.md"
    body.write_text("Summary\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")
    assert rules(shell(f"gh pr create --title x --body-file {body}")) == ["forge-attribution"]


def test_write_tool_on_protected_path(home):
    event = Event(harness="claude", tool="Write", kind="write", cwd="/work", paths=["~/.config/git/config"])
    assert rules(event) == ["machine-config"]


def test_write_tool_on_dotfiles_source_is_allowed(home):
    event = Event(
        harness="claude",
        tool="Write",
        kind="write",
        cwd="/work",
        paths=[str(home / "dotfiles/home/.config/git/config")],
    )
    assert rules(event) == []


def test_allow_env_skips_a_rule(home, monkeypatch):
    monkeypatch.setenv("AGENT_KIT_ALLOW", "machine-config")
    assert rules(shell("echo x >> ~/.ssh/config")) == []


def test_github_mcp_tool_text_is_checked(home):
    event = Event(
        harness="claude",
        tool="mcp__github__create_pull_request",
        kind="other",
        cwd="/w",
        strings=["body \N{ROBOT FACE}"],
    )
    assert rules(event) == ["forge-attribution"]


def test_unparseable_command_fails_open(home):
    assert rules(shell("echo 'oops && python3 x.py")) == []
